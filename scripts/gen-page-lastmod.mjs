// Regenerates lib/page-lastmod.generated.ts — the sitemap's <lastmod> for the
// repository-owned pages whose whole text lives in ONE dedicated content file
// (SEO Step 1, Master Plan §33.3e).
//
// The date is the author date of the last Git commit that touched that content
// file: a real, reproducible content-change date. It is never the build date,
// today's date or a deployment time. A page that has no dedicated content file
// (its words are split across lib/i18n.ts, lib/content/legal.ts or the Hub) is
// NOT listed here, and so the sitemap gives it no <lastmod> at all.
//
// Run by hand after a content file changes, from a full (non-shallow) clone:
//   node scripts/gen-page-lastmod.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

/** bare route -> the content file(s) that hold ALL of the page's text. */
const SOURCES = {
  "/about": ["lib/content/about.ts"],
  "/jewelry-guide": ["lib/content/jewelry-guide.ts"],
};

const git = (...a) => execFileSync("git", a, { encoding: "utf8" }).trim();
if (git("rev-parse", "--is-shallow-repository") === "true") {
  console.error("Shallow clone: Git dates would be wrong. Fetch full history first.");
  process.exit(1);
}

const out = {};
for (const [route, files] of Object.entries(SOURCES)) {
  const iso = git("log", "-1", "--format=%aI", "--", ...files);
  if (!iso) { console.error(`No commit found for ${route}; leaving it out.`); continue; }
  out[route] = iso.slice(0, 10);
}

const body = `// GENERATED by scripts/gen-page-lastmod.mjs — do not edit by hand.
// Last Git content-change date of each page's dedicated content file.
export const PAGE_LASTMOD: Readonly<Record<string, string>> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(new URL("../lib/page-lastmod.generated.ts", import.meta.url), body);
console.log(body);
