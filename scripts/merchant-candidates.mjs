// Read-only helper (public site data only, no Hub key): classifies the live catalog so the owner can confirm identifiers for a SMALL
// initial eligible SKU set instead of the whole catalog. "Eligible except identifiers" = the piece already satisfies every other
// feed rule visible on its public Japanese product page: SKU, JPY price, a Japanese description, a known condition, a known stock state.
// It decides NOTHING about identifiers and writes nothing to the registry. Usage: node scripts/merchant-candidates.mjs [--base URL] [--md out.md]
import { writeFileSync } from "node:fs";
const args = process.argv.slice(2);
const arg = (n, d) => (args.includes(n) ? args[args.indexOf(n) + 1] : d);
const BASE = arg("--base", "https://www.chajewelsjp.com").replace(/\/$/, "");
const sm = await (await fetch(`${BASE}/sitemap.xml`, { signal: AbortSignal.timeout(30000) })).text();
const urls = [...sm.matchAll(/<loc>([^<]+\/ja\/products\/[^<]+)<\/loc>/g)].map((m) => m[1]);
const rows = []; const problems = [];
async function one(u) {
  try {
    const html = await (await fetch(u, { signal: AbortSignal.timeout(30000) })).text();
    for (const m of html.matchAll(/<script type="application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/g)) {
      let d; try { d = JSON.parse(m[1]); } catch { continue; }
      for (const x of Array.isArray(d) ? d : [d]) {
        if (x?.["@type"] !== "Product") continue;
        const o = Array.isArray(x.offers) ? x.offers[0] : x.offers;
        const cond = /UsedCondition/.test(o?.itemCondition ?? "") ? "Preloved" : /NewCondition/.test(o?.itemCondition ?? "") ? "New" : null;
        const stock = /InStock/.test(o?.availability ?? "") ? "in_stock" : /OutOfStock|SoldOut/.test(o?.availability ?? "") ? "out_of_stock" : null;
        const brand = typeof x.brand === "string" ? x.brand : x.brand?.name ?? null;
        rows.push({ sku: x.sku ?? null, url: u, name: x.name ?? null, condition: cond, stock, brand: brand || null, price: typeof o?.price === "number" ? o.price : null, hasDesc: !!(x.description && String(x.description).trim()) });
        return;
      }
    }
    problems.push(u);
  } catch { problems.push(u); }
}
for (let i = 0; i < urls.length; i += 8) await Promise.all(urls.slice(i, i + 8).map(one));
const eligible = rows.filter((r) => r.sku && r.price && r.hasDesc && r.condition && r.stock);
const cls = (r) => `${r.condition === "New" ? "new" : "preloved"}_${r.brand ? "branded" : "no_brand"}`;
const groups = {}; for (const r of eligible) (groups[cls(r)] ??= []).push(r);
for (const g of Object.values(groups)) g.sort((a, b) => (a.stock === b.stock ? a.sku.localeCompare(b.sku) : a.stock === "in_stock" ? -1 : 1));
const summary = { products: urls.length, readable: rows.length, unreadable: problems.length, eligibleExceptIdentifiers: eligible.length, byClass: Object.fromEntries(Object.entries(groups).map(([k, v]) => [k, { total: v.length, inStock: v.filter((r) => r.stock === "in_stock").length }])) };
console.log(JSON.stringify(summary, null, 2));
const md = arg("--md", null);
if (md) {
  const L = [`# Merchant initial eligible SKU pick-list (public data, ${new Date().toISOString().slice(0, 10)})`, "", "Generated by `scripts/merchant-candidates.mjs` from the public Japanese product pages (no Hub key). It lists pieces that already satisfy every other feed rule; it says NOTHING about identifiers. **Pick a small initial set (suggest 5–20 SKUs across the classes you actually sell) and confirm each one's brand and MPN/GTIN in `lib/merchant-confirmed-identifiers.ts` with a note saying who confirmed it and when.** Everything else stays excluded.", "", "```json", JSON.stringify(summary, null, 2), "```", ""];
  for (const [k, v] of Object.entries(groups)) { L.push(`## ${k} (${v.length}; first 12, in-stock first)`, "", "| SKU | Stock | Hub brand | Price (JPY) | Page |", "|---|---|---|---|---|"); for (const r of v.slice(0, 12)) L.push(`| ${r.sku} | ${r.stock} | ${r.brand ?? "—"} | ${r.price} | ${r.url.replace(BASE, "")} |`); L.push(""); }
  writeFileSync(md, L.join("\n"));
}
